describe('parseGemfileLock', () => {
  const fixture = `GIT
  remote: https://github.com/rails/rails.git
  revision: abc
  specs:
    rails (7.0.4.3)
      railties (= 7.0.4.3)

GEM
  remote: https://rubygems.org/
  specs:
    rails (7.0.8)
      actionmailer (= 7.0.8)
      actionpack (= 7.0.8)
    actionmailer (7.0.8)
      actionpack (= 7.0.8)
    actionpack (7.0.8)
    rake (13.0.6)

PLATFORMS
  ruby

DEPENDENCIES
  rails (~> 7.0)
  rake
`;

  const pkgs = LP.parseGemfileLock(fixture);

  test('finds rails',        () => expect(pkg(pkgs, 'rails')).toBeDefined());
  test('finds actionmailer', () => expect(pkg(pkgs, 'actionmailer')).toBeDefined());
  test('finds rake',         () => expect(pkg(pkgs, 'rake')).toBeDefined());
  test('rails version',      () => expect(pkg(pkgs, 'rails').version).toBe('7.0.8'));
  test('rake version',       () => expect(pkg(pkgs, 'rake').version).toBe('13.0.6'));
  test('ecosystem gem',      () => expect(pkg(pkgs, 'rails').ecosystem).toBe('gem'));
  test('GIT section NOT parsed (different indentation)', () => {
    // rails from GIT section has different indentation; GEM section rails is 7.0.8
    const r = pkg(pkgs, 'rails');
    expect(r.version).toBe('7.0.8');
  });
});

