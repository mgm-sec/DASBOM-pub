  const pkgs = LP.parsePoetryLock(fixture);

  test('finds requests',           () => expect(pkg(pkgs, 'requests')).toBeDefined());
  test('finds certifi',            () => expect(pkg(pkgs, 'certifi')).toBeDefined());
  test('requests version',         () => expect(pkg(pkgs, 'requests').version).toBe('2.28.0'));
