describe('isLockfile', () => {
  test('package-lock.json → true', () => expect(LP.isLockfile('package-lock.json')).toBe(true));
  test('yarn.lock → true',         () => expect(LP.isLockfile('yarn.lock')).toBe(true));
  test('poetry.lock → true',       () => expect(LP.isLockfile('poetry.lock')).toBe(true));
  test('Cargo.lock → true',        () => expect(LP.isLockfile('Cargo.lock')).toBe(true));
  test('composer.lock → true',     () => expect(LP.isLockfile('composer.lock')).toBe(true));
  test('go.mod → true',            () => expect(LP.isLockfile('go.mod')).toBe(true));
  test('Gemfile.lock → true',      () => expect(LP.isLockfile('Gemfile.lock')).toBe(true));
  test('subdirectory path → true', () => expect(LP.isLockfile('apps/api/package-lock.json')).toBe(true));
  test('package.json → false',     () => expect(LP.isLockfile('package.json')).toBe(false));
  test('random.txt → false',       () => expect(LP.isLockfile('random.txt')).toBe(false));
  test('Cargo.toml → false',       () => expect(LP.isLockfile('Cargo.toml')).toBe(false));
  test('go.sum → false',           () => expect(LP.isLockfile('go.sum')).toBe(false));
  test('empty string → false',     () => expect(LP.isLockfile('')).toBe(false));
});

describe('detectAndParse', () => {
  test('package-lock.json dispatches correctly', () => {
    const json = JSON.stringify({ lockfileVersion: 2, packages: { 'node_modules/foo': { version: '1.0.0' } } });
    const r = LP.detectAndParse('path/to/package-lock.json', json);
    expect(r).not.toBeNull();
    expect(r[0].name).toBe('foo');
  });

  test('unknown file returns null', () => {
    expect(LP.detectAndParse('package.json', '{}')).toBeNull();
  });

  test('Cargo.lock dispatches correctly', () => {
    const r = LP.detectAndParse('Cargo.lock', '[[package]]\nname = "serde"\nversion = "1.0.0"\n');
    expect(r).not.toBeNull();
    expect(r[0].ecosystem).toBe('cargo');
  });
});
