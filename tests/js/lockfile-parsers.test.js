// ─────────────────────────────────────────────────────────────────────────────
// composer.lock
// ─────────────────────────────────────────────────────────────────────────────
describe('parseComposerLock', () => {
  const fixture = JSON.stringify({
    '_readme': ['Autogenerated'],
    'packages': [
      { name: 'symfony/console', version: 'v6.2.7', require: { 'symfony/string': '^6.0', 'php': '>=8.1' } },
      { name: 'psr/log', version: '3.0.0', require: {} },
    ],
    'packages-dev': [
      { name: 'phpunit/phpunit', version: '10.1.0', require: { 'psr/log': '^3.0', 'ext-dom': '*' } },
    ],
  });

  const pkgs = LP.parseComposerLock(fixture);

  test('finds symfony/console', () => expect(pkg(pkgs, 'symfony')).toBeDefined());
  test('finds psr/log',          () => expect(pkg(pkgs, 'psr/log')).toBeDefined());
  test('finds phpunit (dev)',     () => expect(pkg(pkgs, 'phpunit')).toBeDefined());
  test('symfony version strips v', () => expect(pkg(pkgs, 'symfony').version).toBe('6.2.7'));
  test('psr/log version',          () => expect(pkg(pkgs, 'psr/log').version).toBe('3.0.0'));
  test('ecosystem composer',       () => expect(pkg(pkgs, 'symfony').ecosystem).toBe('composer'));
  test('php excluded from deps',   () => expect(pkg(pkgs, 'symfony').deps).not.toContain('php'));
  test('ext-dom excluded from deps', () => expect(pkg(pkgs, 'phpunit').deps).not.toContain('ext-dom'));
  test('symfony/string in deps',   () => expect(pkg(pkgs, 'symfony').deps).toContain('symfony/string'));
  test('phpunit dep on psr/log',   () => expect(pkg(pkgs, 'phpunit').deps).toContain('psr/log'));
  test('invalid JSON returns []',  () => expect(LP.parseComposerLock('not json')).toEqual([]));
});

