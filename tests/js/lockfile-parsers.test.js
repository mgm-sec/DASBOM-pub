/**
 * Tests for output/viz/lib/lockfile-parsers.js
 *
 * All fixtures are inline strings to avoid file I/O.
 * Each parser returns Array<{name, version, deps, ecosystem}>.
 */

const LP = require('../../output/viz/lib/lockfile-parsers.js');

// ── Helpers ──────────────────────────────────────────────────────────────────

function pkg(list, name) { return list.find(p => p.name === name || p.name.includes(name)); }
function names(list) { return list.map(p => p.name); }

// ─────────────────────────────────────────────────────────────────────────────
// package-lock.json (npm v2)
// ─────────────────────────────────────────────────────────────────────────────
describe('parsePackageLockJson', () => {
  const fixture = JSON.stringify({
    name: 'my-app', version: '1.0.0', lockfileVersion: 2,
    packages: {
      '': { name: 'my-app', version: '1.0.0' },
      'node_modules/lodash': { version: '4.17.21', resolved: 'https://r.tgz' },
      'node_modules/express': { version: '4.18.2', dependencies: { lodash: '^4.0.0' }, peerDependencies: { debug: '*' } },
      'node_modules/express/node_modules/debug': { version: '2.6.9' },
    }
  });

  const pkgs = LP.parsePackageLockJson(fixture);

  test('skips root entry', () => expect(names(pkgs)).not.toContain(''));
  test('finds lodash',   () => expect(pkg(pkgs, 'lodash')).toBeDefined());
  test('finds express',  () => expect(pkg(pkgs, 'express')).toBeDefined());
  test('lodash version', () => expect(pkg(pkgs, 'lodash').version).toBe('4.17.21'));
  test('express version',() => expect(pkg(pkgs, 'express').version).toBe('4.18.2'));
  test('ecosystem npm',  () => expect(pkg(pkgs, 'lodash').ecosystem).toBe('npm'));
  test('express deps include lodash', () => expect(pkg(pkgs, 'express').deps).toContain('lodash'));
  test('peerDep included in deps', () => expect(pkg(pkgs, 'express').deps).toContain('debug'));
  test('nested node_modules parsed (debug)', () => expect(pkg(pkgs, 'debug')).toBeDefined());
  test('invalid JSON returns []', () => expect(LP.parsePackageLockJson('not json')).toEqual([]));
  test('empty packages returns []', () => expect(LP.parsePackageLockJson(JSON.stringify({ lockfileVersion: 2, packages: { '': {} } }))).toEqual([]));
});

// ─────────────────────────────────────────────────────────────────────────────
// yarn.lock v1
// ─────────────────────────────────────────────────────────────────────────────
describe('parseYarnLockV1', () => {
  const fixture = `# THIS IS AN AUTOGENERATED FILE.
# DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

lodash@^4.0.0, lodash@^4.17.0:
  version "4.17.21"
  resolved "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc==

express@^4.18.0:
  version "4.18.2"
  resolved "https://registry.npmjs.org/express/-/express-4.18.2.tgz"
  dependencies:
    lodash "^4.0.0"
    debug "^2.0.0"

debug@^2.0.0:
  version "2.6.9"
`;

  const pkgs = LP.parseYarnLockV1(fixture);

  test('finds lodash',    () => expect(pkg(pkgs, 'lodash')).toBeDefined());
  test('finds express',   () => expect(pkg(pkgs, 'express')).toBeDefined());
  test('finds debug',     () => expect(pkg(pkgs, 'debug')).toBeDefined());
  test('lodash version',  () => expect(pkg(pkgs, 'lodash').version).toBe('4.17.21'));
  test('express version', () => expect(pkg(pkgs, 'express').version).toBe('4.18.2'));
  test('debug version',   () => expect(pkg(pkgs, 'debug').version).toBe('2.6.9'));
  test('deduped — lodash appears once', () => expect(pkgs.filter(p => p.name === 'lodash').length).toBe(1));
  test('express deps',    () => expect(pkg(pkgs, 'express').deps).toContain('lodash'));
  test('express dep debug', () => expect(pkg(pkgs, 'express').deps).toContain('debug'));
  test('ecosystem npm',   () => expect(pkg(pkgs, 'lodash').ecosystem).toBe('npm'));
});

describe('parseYarnLock dispatches v1', () => {
  test('plain yarn.lock treated as v1', () => {
    const r = LP.parseYarnLock('lodash@^4.0.0:\n  version "4.17.21"\n');
    expect(r.length).toBeGreaterThan(0);
  });
});

